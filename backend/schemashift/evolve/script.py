"""Render an ``EvolutionPlan`` as an executable Python script (pymongo)."""

from __future__ import annotations

import textwrap
from pathlib import Path
from typing import Any

from schemashift.codegen.emit import PY_IMPORTS
from schemashift.evolve.model import EvolutionPlan, MigrationStep

RUNTIME = Path(__file__).with_name("runtime.py")

HEADER = '''"""Incremental MongoDB migration generated by SchemaShift (Phase 22). Review before
running.

``apply(db)`` runs the steps in order; ``rollback(db)`` undoes them in reverse order for every
step that has a
rollback. Steps marked MANUAL are never run automatically: ``apply`` stops there and says what to
do.
Irreversible steps list a recovery strategy: take the snapshot first.
"""
'''

TAIL = '''

class ManualStepRequired(RuntimeError):
    """A step SchemaShift cannot automate; its description says what to do."""


def apply(db, log=print, skip_manual=False):
    done = []
    for step in STEPS:
        if step["manual"]:
            if skip_manual:
                log(f"SKIP   {step['id']} (manual): {step['description']}")
                continue
            raise ManualStepRequired(f"{step['id']}: {step['description']}. {step['recovery']}")
        log(f"APPLY  {step['id']} {step['kind']}: {step['description']}")
        APPLY[step["id"]](db)
        done.append(step["id"])
    return done


def rollback(db, log=print):
    undone = []
    for step in reversed(STEPS):
        fn = ROLLBACK.get(step["id"])
        if fn is None:
            log(f"NOTE   {step['id']} cannot be rolled back automatically: {step['recovery'] or
            step['reason']}")
            continue
        log(f"UNDO   {step['id']} {step['kind']}: {step['description']}")
        fn(db)
        undone.append(step["id"])
    return undone
'''


def _body(code: str) -> str:
    lines = code.splitlines() or ["pass"]
    return textwrap.indent("\n".join(lines), "    ")


def _meta(step: MigrationStep) -> dict[str, Any]:
    return {
        "id": step.id,
        "kind": step.kind,
        "collection": step.collection,
        "description": step.description,
        "depends_on": list(step.depends_on),
        "reversibility": step.reversibility,
        "reason": step.reason,
        "manual": step.manual,
        "recovery": step.recovery,
        "saved_data": step.saved_data,
    }


def render_script(plan: EvolutionPlan) -> str:
    """Python source of the incremental migration (the runtime is embedded verbatim)."""
    runtime = RUNTIME.read_text(encoding="utf-8")
    runtime = runtime.split("from __future__ import annotations\n", 1)[1].lstrip("\n")
    out = [HEADER, "from __future__ import annotations\n", "import sys\n", PY_IMPORTS, runtime]
    out.append("\nevolve_runtime = sys.modules[__name__]\n")
    out.append(f"STEPS = {_py(_meta_list(plan))}\n")
    for step in plan.steps:
        if step.manual:
            continue
        out.append(f"\ndef step_{step.id}(db):\n{_body(step.code)}\n")
        if step.rollback:
            out.append(f"\ndef rollback_{step.id}(db):\n{_body(step.rollback)}\n")
    apply_map = ", ".join(f'"{s.id}": step_{s.id}' for s in plan.steps if not s.manual)
    roll_map = ", ".join(
        f'"{s.id}": rollback_{s.id}' for s in plan.steps if s.rollback and not s.manual
    )
    out.append(f"\nAPPLY = {{{apply_map}}}\nROLLBACK = {{{roll_map}}}\n")
    out.append(TAIL)
    return "\n".join(out)


def _meta_list(plan: EvolutionPlan) -> list[dict[str, Any]]:
    return [_meta(s) for s in plan.steps]


def _py(value: Any) -> str:
    import pprint

    return pprint.pformat(value, width=100, sort_dicts=False)
