def test_migration_plan_describes_every_table() -> None:
    result = compile_sql(SQL)
    plan = migration_plan(
        result.schema_, build_layouts(result.graph, result.plan), CompileOptions()
    )
    assert set(plan["tables"]) == {"customers", "orders"}
    assert plan["tables"]["customers"]["identity"] == ["id"]
    assert plan["tables"]["orders"]["columns"]["note"]["nullable"] is True
    assert plan["roots"] == sorted(n for n, t in plan["tables"].items() if t["kind"] == "root")


def test_helper_plan_has_relationships_defaults_and_unique_keys() -> None:
    result = compile_sql(
        SQL
        + "CREATE TABLE u (id INT PRIMARY KEY, e TEXT UNIQUE, d TIMESTAMP DEFAULT '2024-01-01');",
        options=REFERENCED,
    )
    plan = helper_plan(result, build_layouts(result.graph, result.plan), REFERENCED)
    rel = plan["relationships"][0]
    assert (rel["child"], rel["parent"], rel["on_delete"], rel["embedded"]) == (
        "orders",
        "customers",
        "CASCADE",
        False,
    )
    assert plan["defaults"]["orders"]["status"] == {"kind": "literal", "value": "new"}
    assert plan["defaults"]["customers"]["created"]["kind"] == "now"
    assert plan["unique"]["u"] == [["e"]]


