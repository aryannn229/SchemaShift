def test_emitters_can_be_selected() -> None:
    result = compile_sql(SQL, QUERIES)
    only_js = generate_code(result, emitters=(MongoshEmitter(),), run_id="x", timestamp="t")
    assert {f.language for f in only_js.files} == {
        "javascript",
        "python",
    }  # migration + helpers always
    assert sum(f.language == "javascript" for f in only_js.files) == 3
    only_py = generate_code(result, emitters=(PymongoEmitter(),), run_id="x", timestamp="t")
    assert not any(f.language == "javascript" for f in only_py.files)


