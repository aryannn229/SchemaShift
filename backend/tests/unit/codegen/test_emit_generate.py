SQL = """
CREATE TABLE customers (id SERIAL PRIMARY KEY, name TEXT NOT NULL, created TIMESTAMPTZ DEFAULT now());
CREATE TABLE orders (
  id INT PRIMARY KEY, customer_id INT NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  status TEXT DEFAULT 'new', note TEXT, CONSTRAINT ck CHECK (upper(status) = status)
);
"""
QUERIES = """
SELECT c.name, COUNT(*) AS n FROM customers c JOIN orders o ON o.customer_id = c.id GROUP BY c.name;
BEGIN;
INSERT INTO customers (id, name) VALUES (1, 'a');
INSERT INTO orders (id, customer_id) VALUES (1, 1);
COMMIT;
SELECT * FROM ghosts;
"""


REFERENCED = CompileOptions(
    relationship_overrides={"fk:orders.customer_id->customers.id": "REFERENCE"}
)


@pytest.fixture(scope="module")
def generated():  # type: ignore[no-untyped-def]
    options = REFERENCED
    result = compile_sql(SQL, QUERIES, "", options)
    return result, generate_code(result, options, run_id="r1", timestamp="2026-01-01T00:00:00Z")


