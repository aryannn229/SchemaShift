def test_generated_files_embed_the_runtime_sources_verbatim(generated) -> None:  # type: ignore[no-untyped-def]
    from schemashift.codegen.helpers import MARKER
    from schemashift.codegen.helpers import RUNTIME as HELPERS_RUNTIME
    from schemashift.codegen.migration import RUNTIME as MIGRATION_RUNTIME

    _, out = generated
    for generated_path, runtime_path in (
        ("python/migrate.py", MIGRATION_RUNTIME),
        ("python/helpers.py", HELPERS_RUNTIME),
    ):
        source = runtime_path.read_text(encoding="utf-8")
        body = source[source.index(MARKER) :]
        assert body in out.file(generated_path).content
